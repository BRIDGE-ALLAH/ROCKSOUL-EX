import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { bootstrapStore, readStoreFile, listMissions, openMissionRecord, saveHandoff, appendEvidence } from '../src/infrastructure/rocksoul-store.js';
import { inspectWorkspace } from '../src/infrastructure/workspace-inspector.js';
import { createMission, changeMissionStatus } from '../src/application/mission-service.js';

async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'rocksoul-ex-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  return root;
}

test('inspection is bounded and excludes credentials, dependencies, and binary files', async (t) => {
  const root = await fixture(t);
  await fs.mkdir(path.join(root, 'src'), { recursive: true });
  await fs.mkdir(path.join(root, 'node_modules', 'private-pkg'), { recursive: true });
  await fs.writeFile(path.join(root, 'README.md'), '# Fixture\n');
  await fs.writeFile(path.join(root, 'package.json'), '{"name":"fixture","scripts":{"test":"node --test"}}');
  await fs.writeFile(path.join(root, '.env'), 'TOKEN=do-not-read');
  await fs.writeFile(path.join(root, 'src', 'index.js'), 'export const answer = 42;');
  await fs.writeFile(path.join(root, 'src', 'image.png'), Buffer.from([0, 1, 2, 3]));
  await fs.writeFile(path.join(root, 'node_modules', 'private-pkg', 'index.js'), 'secret dependency');

  const result = await inspectWorkspace(root, { maxDepth: 5, maxFiles: 100, maxFileBytes: 4096, maxTotalBytes: 16384 });
  const paths = result.files.map((item) => item.path);
  assert.ok(paths.includes('README.md'));
  assert.ok(paths.includes('package.json'));
  assert.ok(paths.includes('src/index.js'));
  assert.ok(!paths.includes('.env'));
  assert.ok(!paths.some((item) => item.includes('node_modules')));
  assert.ok(!paths.includes('src/image.png'));
  assert.ok(result.skipped.some((item) => item.path === '.env'));
});

test('bootstrap creates missing memory without overwriting user content', async (t) => {
  const root = await fixture(t);
  await fs.mkdir(path.join(root, '.rocksoul'), { recursive: true });
  await fs.writeFile(path.join(root, '.rocksoul', 'DNA.md'), '# My existing DNA\n');
  const result = await bootstrapStore(root);
  assert.ok(result.created.includes('PROJECT.md'));
  assert.ok(result.existing.includes('DNA.md'));
  assert.equal(await fs.readFile(path.join(root, '.rocksoul', 'DNA.md'), 'utf8'), '# My existing DNA\n');
});

test('mission create, status update, reopen, and evidence form a durable local round trip', async (t) => {
  const root = await fixture(t);
  await bootstrapStore(root);
  const created = await createMission(root, {
    title: 'Test local mission',
    goal: 'Persist a reviewable unit of work.',
    scope: ['src/'],
    outOfScope: ['network access'],
    acceptanceCriteria: ['Mission is saved as Markdown', 'Index points to the mission'],
    risks: ['Index may become stale']
  }, '2026-11-08T08:00:00.000Z');
  assert.equal(created.mission.status, 'Draft');
  await changeMissionStatus(root, created.mission.id, 'Ready', '2026-11-08T08:01:00.000Z');
  await changeMissionStatus(root, created.mission.id, 'In Progress', '2026-11-08T08:02:00.000Z');
  const opened = await openMissionRecord(root, created.mission.id);
  assert.match(opened.content, /Test local mission/);
  assert.equal(opened.record.status, 'In Progress');
  assert.equal((await listMissions(root)).length, 1);
  await appendEvidence(root, { id: 'proof-test', missionId: created.mission.id, status: 'passed', exitCode: 0 });
  assert.match(await readStoreFile(root, 'evidence/index.json'), /proof-test/);
});

test('handoff refuses to overwrite a file without the ROCKSOUL ownership marker', async (t) => {
  const root = await fixture(t);
  await fs.mkdir(path.join(root, '.rocksoul', 'sessions'), { recursive: true });
  await fs.writeFile(path.join(root, '.rocksoul', 'sessions', 'latest.md'), '# User notes\n');
  await assert.rejects(() => saveHandoff(root, '<!-- Generated by ROCKSOUL-EX -->\nNew'), /not ROCKSOUL-owned/);
  assert.equal(await fs.readFile(path.join(root, '.rocksoul', 'sessions', 'latest.md'), 'utf8'), '# User notes\n');
});
