import test from 'node:test';
import assert from 'node:assert/strict';
import { canTransition, transitionMission, validateMission, slugify, missionMarkdown } from '../src/domain/mission.js';

const valid = {
  title: 'Build workspace witness',
  goal: 'Produce a bounded project map.',
  scope: ['src/'],
  outOfScope: ['network calls'],
  acceptanceCriteria: ['Secrets are excluded', 'The report lists skipped paths'],
  risks: ['Large repositories may be partial']
};

test('mission validation requires a title, goal, and at least one acceptance criterion', () => {
  assert.equal(validateMission(valid).valid, true);
  assert.equal(validateMission({ ...valid, acceptanceCriteria: [] }).valid, false);
  assert.equal(validateMission({ ...valid, title: '  ' }).valid, false);
});

test('mission state machine rejects skipping directly from Draft to Verified', () => {
  assert.equal(canTransition('Draft', 'Ready'), true);
  assert.equal(canTransition('Draft', 'Verified'), false);
  assert.throws(() => transitionMission({ status: 'Draft' }, 'Verified'), /cannot move/);
});

test('mission markdown is human-readable, marked, and preserves criteria', () => {
  const mission = { ...valid, id: 'rsx-test', status: 'Draft', createdAt: '2026-01-01T00:00:00.000Z', updatedAt: '2026-01-01T00:00:00.000Z', evidenceIds: [] };
  const markdown = missionMarkdown(mission);
  assert.match(markdown, /Generated by ROCKSOUL-EX/);
  assert.match(markdown, /Secrets are excluded/);
  assert.match(markdown, /Build workspace witness/);
});

test('slugification is stable for human-readable identifiers', () => {
  assert.equal(slugify('ROCKSOUL EX — Mission 01'), 'rocksoul-ex-mission-01');
});
