export const MISSION_STATUSES = Object.freeze([
  'Draft', 'Ready', 'In Progress', 'Needs Review', 'Implemented',
  'Verifying', 'Verified', 'Failed', 'Blocked', 'Deferred', 'Closed'
]);

const TRANSITIONS = Object.freeze({
  Draft: new Set(['Ready', 'Deferred', 'Closed']),
  Ready: new Set(['In Progress', 'Deferred', 'Closed']),
  'In Progress': new Set(['Needs Review', 'Implemented', 'Verifying', 'Blocked', 'Deferred', 'Closed']),
  'Needs Review': new Set(['In Progress', 'Implemented', 'Deferred', 'Closed']),
  Implemented: new Set(['Verifying', 'In Progress', 'Deferred', 'Closed']),
  Verifying: new Set(['Implemented', 'Verified', 'Failed', 'Blocked', 'In Progress']),
  Verified: new Set(['In Progress', 'Closed']),
  Failed: new Set(['In Progress', 'Verifying', 'Deferred', 'Closed']),
  Blocked: new Set(['In Progress', 'Deferred', 'Closed']),
  Deferred: new Set(['Draft', 'Ready', 'In Progress', 'Closed']),
  Closed: new Set([])
});

export function slugify(value) {
  return String(value ?? '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48) || 'mission';
}

export function normalizeLines(value) {
  return String(value ?? '').split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
}

export function validateMission(input) {
  const errors = [];
  if (!String(input?.title ?? '').trim()) errors.push('Mission title is required.');
  if (!String(input?.goal ?? '').trim()) errors.push('Mission goal is required.');
  const criteria = Array.isArray(input?.acceptanceCriteria) ? input.acceptanceCriteria.filter((item) => String(item).trim()) : [];
  if (criteria.length === 0) errors.push('At least one acceptance criterion is required.');
  const scope = Array.isArray(input?.scope) ? input.scope.filter((item) => String(item).trim()) : [];
  const exclusions = Array.isArray(input?.outOfScope) ? input.outOfScope.filter((item) => String(item).trim()) : [];
  return { valid: errors.length === 0, errors, normalized: { ...input, title: String(input?.title ?? '').trim(), goal: String(input?.goal ?? '').trim(), scope, outOfScope: exclusions, acceptanceCriteria: criteria } };
}

export function canTransition(from, to) {
  return Boolean(TRANSITIONS[from]?.has(to));
}

export function transitionMission(mission, nextStatus, now = new Date().toISOString()) {
  if (!MISSION_STATUSES.includes(nextStatus)) throw new Error(`Unknown mission status: ${nextStatus}`);
  if (!canTransition(mission.status, nextStatus)) throw new Error(`Mission cannot move from ${mission.status} to ${nextStatus}.`);
  return { ...mission, status: nextStatus, updatedAt: now };
}

export function missionMarkdown(mission) {
  const bullets = (items) => items.length ? items.map((item) => `- ${item}`).join('\n') : '- None recorded';
  return `<!-- Generated by ROCKSOUL-EX. You may edit this mission. -->\n# ${mission.title}\n\n- **ID:** \`${mission.id}\`\n- **Status:** ${mission.status}\n- **Created:** ${mission.createdAt}\n- **Updated:** ${mission.updatedAt}\n\n## Goal\n\n${mission.goal}\n\n## In scope\n\n${bullets(mission.scope)}\n\n## Out of scope\n\n${bullets(mission.outOfScope)}\n\n## Acceptance criteria\n\n${mission.acceptanceCriteria.map((item) => `- [ ] ${item}`).join('\n')}\n\n## Risks and assumptions\n\n${bullets(mission.risks)}\n\n## Evidence\n\n${mission.evidenceIds?.length ? mission.evidenceIds.map((id) => `- \`${id}\``).join('\n') : '- No verification evidence recorded yet.'}\n`;
}
